-- 1. Create table `art_gallery`
CREATE TABLE IF NOT EXISTS public.art_gallery (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title TEXT NOT NULL,
    price TEXT NOT NULL,
    medium TEXT NOT NULL,
    src TEXT NOT NULL,
    thumb TEXT NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL
);

-- 2. Enable Row Level Security (RLS)
ALTER TABLE public.art_gallery ENABLE ROW LEVEL SECURITY;

-- 3. Drop existing policies if they already exist to avoid errors
DROP POLICY IF EXISTS "Public can view artworks" ON public.art_gallery;
DROP POLICY IF EXISTS "Enable insert for all users" ON public.art_gallery;
DROP POLICY IF EXISTS "Enable delete for all users" ON public.art_gallery;
DROP POLICY IF EXISTS "Enable update for all users" ON public.art_gallery;

-- 4. Create RLS Policies for `art_gallery` table
CREATE POLICY "Public can view artworks" 
ON public.art_gallery FOR SELECT 
USING (true);

CREATE POLICY "Enable insert for all users" 
ON public.art_gallery FOR INSERT 
WITH CHECK (true);

CREATE POLICY "Enable delete for all users" 
ON public.art_gallery FOR DELETE 
USING (true);

CREATE POLICY "Enable update for all users" 
ON public.art_gallery FOR UPDATE 
USING (true);

-- 5. Set up storage bucket `arts`
INSERT INTO storage.buckets (id, name, public)
VALUES ('arts', 'arts', true)
ON CONFLICT (id) DO UPDATE SET public = true;

-- 6. Storage Policies for `arts` bucket
DROP POLICY IF EXISTS "Public access to arts bucket" ON storage.objects;
DROP POLICY IF EXISTS "Public insert to arts bucket" ON storage.objects;
DROP POLICY IF EXISTS "Public delete from arts bucket" ON storage.objects;
DROP POLICY IF EXISTS "Public update to arts bucket" ON storage.objects;

CREATE POLICY "Public access to arts bucket"
ON storage.objects FOR SELECT
USING (bucket_id = 'arts');

CREATE POLICY "Public insert to arts bucket"
ON storage.objects FOR INSERT
WITH CHECK (bucket_id = 'arts');

CREATE POLICY "Public delete from arts bucket"
ON storage.objects FOR DELETE
USING (bucket_id = 'arts');

CREATE POLICY "Public update to arts bucket"
ON storage.objects FOR UPDATE
USING (bucket_id = 'arts');

